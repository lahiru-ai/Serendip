-- Language: SQL (Data Definition Language)
-- Purpose: Creates base 'users' table storing shared credentials, role discriminator, and account status for joined-table inheritance.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    phone_number VARCHAR(30),
    role VARCHAR(31) NOT NULL,
    account_status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Buyers joined sub-table
CREATE TABLE IF NOT EXISTS buyers (
    user_id BIGINT NOT NULL PRIMARY KEY,
    delivery_address VARCHAR(255),
    CONSTRAINT fk_buyers_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- 3. Sellers joined sub-table
CREATE TABLE IF NOT EXISTS sellers (
    user_id BIGINT NOT NULL PRIMARY KEY,
    shop_name VARCHAR(150) NOT NULL,
    shop_description VARCHAR(1000),
    origin_city VARCHAR(100) DEFAULT 'Colombo',
    commission_rate DECIMAL(5, 2) NOT NULL DEFAULT 10.00,
    CONSTRAINT fk_sellers_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- 4. Admins joined sub-table
CREATE TABLE IF NOT EXISTS admins (
    user_id BIGINT NOT NULL PRIMARY KEY,
    department VARCHAR(100),
    CONSTRAINT fk_admins_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- 5. Products catalog table
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id BIGINT NOT NULL,
    name VARCHAR(180) NOT NULL,
    category VARCHAR(100) DEFAULT 'General',
    description VARCHAR(2000),
    price_usd DECIMAL(12, 2) NOT NULL,
    price_lkr DECIMAL(14, 2),
    currency_code VARCHAR(3) NOT NULL DEFAULT 'USD',
    stock_quantity INT NOT NULL DEFAULT 0,
    weight_grams INT DEFAULT 100,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_products_seller FOREIGN KEY (seller_id) REFERENCES sellers (user_id)
);
CREATE INDEX IF NOT EXISTS idx_products_seller ON products (seller_id);
CREATE INDEX IF NOT EXISTS idx_products_category ON products (category);

-- 6. Shopping carts table (One-to-One with Buyer)
CREATE TABLE IF NOT EXISTS shopping_carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id BIGINT NOT NULL UNIQUE,
    CONSTRAINT fk_shopping_carts_buyer FOREIGN KEY (buyer_id) REFERENCES buyers (user_id) ON DELETE CASCADE
);

-- 7. Cart items table (Composition with ShoppingCart)
CREATE TABLE IF NOT EXISTS cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INT NOT NULL DEFAULT 1,
    unit_price DECIMAL(12, 2) NOT NULL,
    CONSTRAINT fk_cart_items_cart FOREIGN KEY (cart_id) REFERENCES shopping_carts (id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_items_product FOREIGN KEY (product_id) REFERENCES products (id)
);
CREATE INDEX IF NOT EXISTS idx_cart_items_cart ON cart_items (cart_id);

-- 8. Orders table (Parent multi-vendor checkout order)
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(64) NOT NULL UNIQUE,
    buyer_id BIGINT NOT NULL,
    shipping_address VARCHAR(500) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'USD',
    subtotal_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    shipping_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    tax_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    total_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING_PAYMENT',
    payment_method VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_orders_buyer FOREIGN KEY (buyer_id) REFERENCES buyers (user_id)
);
CREATE INDEX IF NOT EXISTS idx_orders_buyer ON orders (buyer_id);

-- 9. Seller sub-orders table (Multi-vendor fulfillment and commission)
CREATE TABLE IF NOT EXISTS seller_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT,
    seller_id BIGINT NOT NULL,
    sub_order_number VARCHAR(64),
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING_PAYMENT',
    subtotal_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    shipping_amount DECIMAL(12, 2) NOT NULL DEFAULT 15.00,
    commission_rate DECIMAL(5, 2) NOT NULL DEFAULT 10.00,
    commission_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    net_payout_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    carrier VARCHAR(64),
    tracking_number VARCHAR(128),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_seller_orders_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_seller_orders_seller FOREIGN KEY (seller_id) REFERENCES sellers (user_id)
);
CREATE INDEX IF NOT EXISTS idx_seller_orders_order ON seller_orders (order_id);
CREATE INDEX IF NOT EXISTS idx_seller_orders_seller ON seller_orders (seller_id);

-- 10. Order items table (Historical price and item snapshot at checkout)
CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    product_name_at_purchase VARCHAR(180) NOT NULL,
    unit_price_at_purchase DECIMAL(12, 2) NOT NULL,
    quantity INT NOT NULL,
    line_total DECIMAL(12, 2) NOT NULL,
    CONSTRAINT fk_order_items_seller_order FOREIGN KEY (seller_order_id) REFERENCES seller_orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id)
);
CREATE INDEX IF NOT EXISTS idx_order_items_seller_order ON order_items (seller_order_id);

-- 11. Payments audit transaction table
CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE,
    payment_method VARCHAR(64) NOT NULL,
    transaction_reference VARCHAR(128) NOT NULL,
    amount DECIMAL(12, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'USD',
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    message VARCHAR(255),
    deposit_slip_url VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_payments_reference ON payments (transaction_reference);

-- 12. Reviews table (Verified purchase reviews)
CREATE TABLE IF NOT EXISTS reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    order_item_id BIGINT,
    rating INT NOT NULL,
    comment VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_reviews_buyer FOREIGN KEY (buyer_id) REFERENCES buyers (user_id),
    CONSTRAINT fk_reviews_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT fk_reviews_order_item FOREIGN KEY (order_item_id) REFERENCES order_items (id)
);
CREATE INDEX IF NOT EXISTS idx_reviews_product ON reviews (product_id);
CREATE INDEX IF NOT EXISTS idx_reviews_buyer ON reviews (buyer_id);

-- 13. Order status history audit table
CREATE TABLE IF NOT EXISTS order_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    seller_order_id BIGINT,
    previous_status VARCHAR(32),
    new_status VARCHAR(32) NOT NULL,
    changed_by_user_id BIGINT,
    changed_by_name VARCHAR(150),
    changed_by_role VARCHAR(32),
    comments VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_history_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_history_seller_order FOREIGN KEY (seller_order_id) REFERENCES seller_orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_history_user FOREIGN KEY (changed_by_user_id) REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_history_order ON order_status_history (order_id);
CREATE INDEX IF NOT EXISTS idx_history_seller_order ON order_status_history (seller_order_id);
CREATE INDEX IF NOT EXISTS idx_history_created_at ON order_status_history (created_at);
